#!/usr/bin/env python3
"""Create or reuse private local Matter credentials and printable pairing codes."""
from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path
import subprocess
import sys

from nordic import installed_tools
from provisioning import ensure


def _number(value: str) -> int:
    try:
        # Decimal input may have leading zeroes; also accept explicit hex.
        return int(value, 16 if value.lower().startswith('0x') else 10)
    except ValueError as exc:
        raise argparse.ArgumentTypeError('expected a decimal integer or 0x-prefixed hex value') from exc


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True,
                        help='private directory to create or reuse; use a new directory for another device')
    parser.add_argument('--passcode', type=_number, help='optional valid Matter passcode; randomly generated by default')
    parser.add_argument('--discriminator', type=_number, help='optional discriminator 1..4095; randomly generated by default')
    parser.add_argument('--sdk', type=Path, help='existing NCS 3.4.1 SDK (or NCS_SDK_ROOT)')
    parser.add_argument('--toolchain', type=Path, help='existing Nordic toolchain (or NCS_TOOLCHAIN_ROOT)')
    args = parser.parse_args()
    try:
        dependencies = {'qrcode': 'qrcode', 'cryptography': 'cryptography', 'PIL': 'Pillow'}
        missing = [name for module, name in dependencies.items() if importlib.util.find_spec(module) is None]
        if missing:
            try:
                _, python, env = installed_tools(args)
            except RuntimeError as exc:
                raise RuntimeError(f'Matter provisioning needs {", ".join(missing)}; {exc}') from exc
            if python.resolve() == Path(sys.executable).resolve():
                raise RuntimeError(f'The installed Nordic Python lacks {", ".join(missing)}. No packages installed.')
            subprocess.run([str(python), str(Path(__file__).resolve()), *sys.argv[1:]], env=env, check=True)
            return
        destination = args.output_dir.expanduser().resolve()
        existed = (destination / 'provisioning.json').exists()
        ensure(destination, passcode=args.passcode, discriminator=args.discriminator)
        print(f'{"Reused" if existed else "Created"} Matter credentials: {destination / "provisioning.json"}')
        print(f'Pairing card: {destination / "pairing.png"}')
        print(f'Pairing QR: {destination / "pairing.svg"}')
        print(f'Pairing details: {destination / "pairing.txt"}')
    except (OSError, RuntimeError, subprocess.CalledProcessError) as exc:
        parser.exit(1, f'Provisioning failed: {exc}\n')


if __name__ == '__main__':
    main()
